def write(path: pathlib.Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def check_installer_preconditions() -> dict:
    """Everything that can refuse to build, before anything is written or deleted.

    **Separate from [stage_installer_assets] because of the order, not the
    tidiness.** These checks used to live inside the staging step, which
    [build_all] calls *after* clearing `site/` — so a refusal left the tree with
    every generated page deleted and nothing to replace them. It happened on
    2026-08-13, with the staged APK belonging to the dev channel and the policy
    pinning the alpha's: the check was right, the site was gone, and only git had
    a copy.

    A tool that destroys its output before deciding whether it may proceed is one
    interrupted afternoon away from being the problem it exists to prevent.

    Returns what it computed, so the staging step does not read the APK twice.
    """
    import base64
    import hashlib
    import json

    apk_src = REPO_ROOT / "dist" / "release" / "dpc-release.apk"
    if not apk_src.exists():
        raise SystemExit(
            f"Missing {apk_src.relative_to(REPO_ROOT)} — run tools/stage-release.sh first.\n"
            "The USB installer page serves this file, so the site cannot be built without it."
        )

    digest = hashlib.sha256(apk_src.read_bytes()).hexdigest()

    policy_path = REPO_ROOT / "dist" / "policy.signed.json"
    payload = json.loads(base64.b64decode(json.loads(policy_path.read_text())["payload"]))
    pinned = (payload.get("app_update") or {}).get("sha256")
    if pinned and pinned != digest:
        raise SystemExit(
            "dist/release/dpc-release.apk does not match the app_update pin in the signed policy.\n"
            f"  policy pins: {pinned}\n"
            f"  staged APK:  {digest}\n"
            "The installer page would hand phones a build the policy does not know about.\n"
            "Stage the published APK, or re-sign the policy against this one.\n"
            "Nothing was changed; site/ is untouched."
        )

    for js in ("adb.js", "installer.js"):
        source = SITE_SRC / "installer" / js
        if not source.exists():
            raise SystemExit(f"Missing {source.relative_to(REPO_ROOT)}; the installer needs it.")

    return {"apk_src": apk_src, "digest": digest}


def stage_installer_assets(checked: dict) -> dict:
    """Copies the DPC and the installer's JS into site/assets/, and pins the APK.

    Two things force the APK to be served from this site rather than linked from
    the GitHub release. GitHub's release downloads carry no
    `Access-Control-Allow-Origin` header, so a browser fetch from the site is
    blocked outright — measured 2026-08-10, through the redirect to
    release-assets.githubusercontent.com. And a page that reached out to a third
    party to fetch what it is about to install would give up the property the
    rest of this site is built on.

    The hash is checked against `app_update` in the signed policy rather than
    merely recomputed, because those two are the same claim made in two places:
    the policy tells provisioned devices which build is current, and this page
    hands that same build to a phone that has none yet. A build where they
    disagree is a build where one of them is lying, so it fails here.
    """
    apk_src = checked["apk_src"]
    digest = checked["digest"]

    assets = SITE_OUT / "assets"
    (assets / "js").mkdir(parents=True, exist_ok=True)

    # The APK is named after its own hash, and that is not cosmetic.
    #
    # The installer page carries the expected checksum inline and refuses to
    # install anything that does not match it. With a stable filename those two
    # are separate URLs with separate cache lifetimes, so a page held in a tab
    # from before a release fetches the *new* APK and refuses it — which is what
    # happened on 2026-08-10, and reads to the person in front of it as the
    # download being corrupt rather than the page being old.
    #
    # Content-addressing removes the failure instead of explaining it: a stale
    # page asks for an APK that no longer exists, and a 404 is something the page
    # can name exactly ("reload this page"). A mismatch now means what it says.
    name = f"dpc-{digest[:16]}.apk"
    for stale in sorted(set(assets.glob("dpc-*.apk"))):
        if stale.name != name:
            stale.unlink()
    shutil.copy2(apk_src, assets / name)
    for js in ("adb.js", "installer.js"):
        shutil.copy2(SITE_SRC / "installer" / js, assets / "js" / js)

    return {"name": name, "sha256": digest, "size": apk_src.stat().st_size}


def build_all() -> None:
    # Before the clear below, never after it: see check_installer_preconditions.
    checked = check_installer_preconditions()

    if SITE_OUT.exists():
        for item in SITE_OUT.iterdir():
            if item.name == "assets":
                continue
            if item.is_dir():
                shutil.rmtree(item)
            else:
                item.unlink()

    import sys
    sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
    import convert_blocklist  # tools/convert_blocklist.py
    why_fragment = convert_blocklist.build_fragment(generated_tables())
    write(SITE_OUT / "why-blocked" / "index.html", render_why_blocked(why_fragment))

    apk = stage_installer_assets(checked)

    for lang in LANGUAGES:
        base = SITE_OUT if lang == "en" else SITE_OUT / lang
        write(base / "index.html", render_home(lang))
        write(base / "install" / "index.html", render_install(lang))
        write(base / "install" / "usb" / "index.html", render_usb_installer(lang, apk))
        write(base / "faq" / "index.html", render_faq(lang))
        if lang in WHY_SUMMARY:
            write(base / "why-blocked" / "index.html", render_why_summary(lang))

    check_internal_links()
    print(f"Built {len(LANGUAGES)} languages into {SITE_OUT}")


def check_internal_links() -> None:
    """Fails the build on a site-internal link with no file behind it.

    Added after the homepage and install page shipped pointing at
    /nl/why-blocked/ and /fr/why-blocked/, which did not exist: the nav had
    been special-cased to the English URL but the in-page buttons had not.
    A 404 in generated output is exactly the kind of thing a generator
    should catch rather than a person.
    """
    import re

    broken: list[str] = []
    for page in sorted(SITE_OUT.rglob("*.html")):
        html = page.read_text(encoding="utf-8")
        for href in re.findall(r'href="(/[^"#]*)"', html):
            target = SITE_OUT / href.lstrip("/")
            if target.suffix:           # a file, e.g. /assets/css/style.css
                ok = target.exists()
            else:                       # a directory URL, e.g. /nl/faq/
                ok = (target / "index.html").exists()
            if not ok:
                broken.append(f"{page.relative_to(SITE_OUT)} -> {href}")

    if broken:
        raise SystemExit(
            "Broken internal links:\n  " + "\n  ".join(broken)
        )


if __name__ == "__main__":
    build_all()
