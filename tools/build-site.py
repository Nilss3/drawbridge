def render_faq(lang: str) -> str:
    c = FAQ[lang]
    parts = []
    for kind, payload in c["blocks"]:
        if kind == "h2":
            parts.append(f"<h2>{payload}</h2>")
        elif kind == "p":
            parts.append(f"<p>{payload}</p>")
        elif kind == "ul":
            items = "\n".join(f"<li>{item}</li>" for item in payload)
            parts.append(f"<ul>\n{items}\n</ul>")
    body = f"""
  <section class="section">
    <div class="wrap">
      <h1>{c['h1']}</h1>
      {chr(10).join(parts)}
    </div>
  </section>
"""
    return render_page(lang=lang, path="faq/", title=c["title"], description=c["description"], body=body)


