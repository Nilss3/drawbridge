def render_page(
    *,
    lang: str,
    path: str,
    title: str,
    description: str,
    body: str,
    lang_switch_targets: dict[str, str] | None = None,
    scripts: str = "",
) -> str:
    """path is the page's own path relative to its language root, e.g. '', 'faq/', 'install/'.

    why-blocked/ is a single English-only page (no point translating ~200
    cited rows into languages nobody has reviewed the legal claims in), so
    every language's nav links to the same canonical /why-blocked/ URL
    rather than a per-language prefix that would not exist.
    """
    prefix = lang_prefix(lang)
    nav = NAV[lang]

    def nav_link(target_path: str, label: str, *, href: str | None = None) -> str:
        resolved = href if href is not None else (f"{prefix}/{target_path}" if target_path else (prefix or "/"))
        active = " aria-current=\"page\"" if target_path == path else ""
        return f'<a href="{resolved}"{active}>{label}</a>'

    nav_html = "\n      ".join([
        nav_link("", nav["home"]),
        nav_link("faq/", nav["faq"]),
        nav_link("install/", nav["install"]),
        f'<a href="https://github.com/Nilss3/drawbridge">{nav["github"]}</a>',
    ])

    switcher_links = []
    for code in LANGUAGES:
        if lang_switch_targets is not None:
            href = lang_switch_targets[code]
        else:
            target_prefix = lang_prefix(code)
            href = f"{target_prefix}/{path}" if path else (target_prefix or "/")
        current = " class=\"lang-current\"" if code == lang else ""
        switcher_links.append(f'<a href="{href}"{current}>{code.upper()}</a>')
    switcher_html = " · ".join(switcher_links)

    home_href = prefix or "/"
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<!-- Generated by tools/build-site.py from site-src/. Do not hand-edit — rerun the build script instead. -->
<meta charset="utf-8" />
<title>{title}</title>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="description" content="{description}" />
<link rel="icon" href="/assets/img/icon.webp" />
<link rel="stylesheet" href="/assets/css/style.css" />
</head>
<body>
<header class="site-header">
  <div class="wrap">
    <a class="brand" href="{home_href}">
      <img src="/assets/img/icon.webp" alt="" />
      drawbridge
    </a>
    <div class="header-right">
      <nav class="nav">
      {nav_html}
      </nav>
      <div class="lang-switch">{switcher_html}</div>
    </div>
  </div>
</header>

<main>
{body}
</main>

<footer class="site-footer">
  <div class="wrap">
    <span>{FOOTER[lang]}</span>
    <span><a href="https://github.com/Nilss3/drawbridge">{FOOTER_SOURCE[lang]}</a></span>
  </div>
</footer>
{scripts}</body>
</html>
"""


def steps_html(items: list[str], start: int = 1) -> str:
    lis = []
    for i, item in enumerate(items, start=start):
        lis.append(f'<li><span class="num">{i}</span><div>{item}</div></li>')
    attr = f' start="{start}"' if start != 1 else ""
    return f'<ol class="steps"{attr}>\n' + "\n".join(lis) + "\n</ol>"


