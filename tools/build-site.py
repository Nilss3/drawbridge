#!/usr/bin/env python3
"""Builds site/ from site-src/. Static output only — no client-side
framework, so Cloudflare Pages serves site/ with no build step configured on
its end. Run this locally after editing site-src/ and commit the result.

    python3 tools/build-site.py

Adding a language means adding one entry to LANGUAGES and one content dict
below; the page functions and layout are language-agnostic.
"""

from __future__ import annotations

import pathlib
import shutil

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
SITE_SRC = REPO_ROOT / "site-src"
SITE_OUT = REPO_ROOT / "site"

# ---------------------------------------------------------------------------
# Languages. English is canonical and lives at the site root; every other
# language gets a /<code>/ prefix, mirroring docs/install.md · install.nl.md
# · install.fr.md elsewhere in this repo.
# ---------------------------------------------------------------------------

# A non-production channel marks every page it renders. site-src/channel.txt
# exists only on the dev branch; main has no such file and renders nothing extra,
# so this costs the published site nothing.
#
# It is not decoration. dev.drawbridge-project.pages.dev and
# drawbridge-project.pages.dev are the same site with different builds behind
# them, one of which provisions phones people are relying on. A page that does
# not say which one it is, is a page somebody will use to flash the wrong build.
CHANNEL = (SITE_SRC / "channel.txt").read_text().strip() if (SITE_SRC / "channel.txt").exists() else ""

LANGUAGES = ["en", "nl", "fr"]
LANG_NAMES = {"en": "English", "nl": "Nederlands", "fr": "Français"}


def lang_prefix(lang: str) -> str:
    return "" if lang == "en" else f"/{lang}"


# ---------------------------------------------------------------------------
# Shared chrome: nav, footer, language switcher.
# ---------------------------------------------------------------------------

NAV = {
    "en": {"home": "Home", "faq": "Q&A", "install": "Install", "github": "GitHub"},
    "nl": {"home": "Home", "faq": "Q&A", "install": "Installeren", "github": "GitHub"},
    "fr": {"home": "Accueil", "faq": "Q&A", "install": "Installer", "github": "GitHub"},
}

FOOTER = {
    "en": "Drawbridge is free and open source (MIT).",
    "nl": "Drawbridge is gratis en open source (MIT).",
    "fr": "Drawbridge est gratuit et open source (MIT).",
}
FOOTER_SOURCE = {"en": "Source on GitHub", "nl": "Broncode op GitHub", "fr": "Code source sur GitHub"}


def channel_banner() -> str:
    """A band across the top of every page on a non-production channel."""
    if not CHANNEL:
        return ""
    return (
        f'<div class="channel-banner">{CHANNEL.upper()} CHANNEL — test builds, '
        "not the release. Do not use a phone you depend on.</div>\n"
    )


def render_page(
    *,
    lang: str,
    path: str,
    title: str,
    description: str,
    body: str,
    lang_switch_targets: dict[str, str] | None = None,
    scripts: str = "",
) -> str:
    """path is the page's own path relative to its language root, e.g. '', 'faq/', 'install/'.

    why-blocked/ is a single English-only page (no point translating ~200
    cited rows into languages nobody has reviewed the legal claims in), so
    every language's nav links to the same canonical /why-blocked/ URL
    rather than a per-language prefix that would not exist.
    """
    prefix = lang_prefix(lang)
    nav = NAV[lang]

    def nav_link(target_path: str, label: str, *, href: str | None = None) -> str:
        resolved = href if href is not None else (f"{prefix}/{target_path}" if target_path else (prefix or "/"))
        active = " aria-current=\"page\"" if target_path == path else ""
        return f'<a href="{resolved}"{active}>{label}</a>'

    nav_html = "\n      ".join([
        nav_link("", nav["home"]),
        nav_link("faq/", nav["faq"]),
        nav_link("install/", nav["install"]),
        f'<a href="https://github.com/Nilss3/drawbridge">{nav["github"]}</a>',
    ])

    switcher_links = []
    for code in LANGUAGES:
        if lang_switch_targets is not None:
            href = lang_switch_targets[code]
        else:
            target_prefix = lang_prefix(code)
            href = f"{target_prefix}/{path}" if path else (target_prefix or "/")
        current = " class=\"lang-current\"" if code == lang else ""
        switcher_links.append(f'<a href="{href}"{current}>{code.upper()}</a>')
    switcher_html = " · ".join(switcher_links)

    home_href = prefix or "/"
    return f"""<!doctype html>
<html lang="{lang}">
<head>
<!-- Generated by tools/build-site.py from site-src/. Do not hand-edit — rerun the build script instead. -->
<meta charset="utf-8" />
<title>{title}</title>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<meta name="description" content="{description}" />
<link rel="icon" href="/assets/img/icon.webp" />
<link rel="stylesheet" href="/assets/css/style.css" />
</head>
<body>
{channel_banner()}<header class="site-header">
  <div class="wrap">
    <a class="brand" href="{home_href}">
      <img src="/assets/img/icon.webp" alt="" />
      drawbridge
    </a>
    <div class="header-right">
      <nav class="nav">
      {nav_html}
      </nav>
      <div class="lang-switch">{switcher_html}</div>
    </div>
  </div>
</header>

<main>
{body}
</main>

<footer class="site-footer">
  <div class="wrap">
    <span>{FOOTER[lang]}</span>
    <span><a href="https://github.com/Nilss3/drawbridge">{FOOTER_SOURCE[lang]}</a></span>
  </div>
</footer>
{scripts}</body>
</html>
"""


def steps_html(items: list[str], start: int = 1) -> str:
    lis = []
    for i, item in enumerate(items, start=start):
        lis.append(f'<li><span class="num">{i}</span><div>{item}</div></li>')
    attr = f' start="{start}"' if start != 1 else ""
    return f'<ol class="steps"{attr}>\n' + "\n".join(lis) + "\n</ol>"


